#!/usr/bin/env python3
"""Generate and verify docs/adr/CATALOG.md from MADR 4.0 ADRs (zero-drift gate).

Modeled on northstar's architecture-catalog generator: validates required metadata,
required MADR sections, and the 45-day revisit threshold across all ADR-*.md files.
"""
from __future__ import annotations

import argparse
import datetime as dt
import pathlib
import re

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
ADR_DIR = REPO_ROOT / "docs" / "adr"
CATALOG_PATH = ADR_DIR / "CATALOG.md"
REVISIT_DAYS = 45

REQUIRED_META = ("Status", "Date", "Layer", "Evidence Grade", "Revisit Trigger")
REQUIRED_SECTIONS = (
    "## Context and Problem Statement",
    "## Decision Outcome",
    "## Alternatives Considered",
    "## Verification Witness",
)


def parse_adr(path: pathlib.Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    title_match = re.search(r"^#\s+(ADR-\d{4}):\s+(.+)$", text, re.MULTILINE)
    if not title_match:
        raise ValueError(f"{path.name}: missing '# ADR-XXXX: Title' heading")

    meta: dict[str, str] = {
        "id": title_match.group(1),
        "title": title_match.group(2).strip(),
        "file": path.name,
    }
    for key in REQUIRED_META:
        m = re.search(rf"^-\s+\*\*{re.escape(key)}:\*\*\s+(.+)$", text, re.MULTILINE)
        if not m:
            raise ValueError(f"{path.name}: missing metadata field '**{key}:**'")
        meta[key] = m.group(1).strip()

    for sec in REQUIRED_SECTIONS:
        if sec not in text:
            raise ValueError(f"{path.name}: missing required section '{sec}'")

    dt.date.fromisoformat(meta["Date"])
    return meta


def render_catalog(rows: list[dict[str, str]]) -> str:
    as_of = max(dt.date.fromisoformat(r["Date"]) for r in rows)
    due = [r["id"] for r in rows if (as_of - dt.date.fromisoformat(r["Date"])).days > REVISIT_DAYS]
    lines = [
        "# SOTA Architecture Decision Catalog (`L0–L11` × `T0–T8`)",
        "",
        "<!-- GENERATED by scripts/architecture_catalog.py; do not edit by hand. -->",
        "",
        f"- **ADR Count:** {len(rows)} Accepted",
        f"- **Revisit Threshold:** {REVISIT_DAYS} days",
        f"- **Due for Revisit:** {', '.join(due) if due else 'None'}",
        "",
        "| ADR | Layer | Title | Status | Date | Grade | Revisit Trigger |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| [{r['id']}]({r['file']}) | {r['Layer']} | {r['title']} | {r['Status']} | {r['Date']} | {r['Evidence Grade']} | {r['Revisit Trigger']} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Build or check docs/adr/CATALOG.md")
    parser.add_argument("--check", action="store_true", help="Verify CATALOG.md is up to date without writing")
    args = parser.parse_args()

    adr_files = sorted(ADR_DIR.glob("ADR-[0-9][0-9][0-9][0-9]-*.md"))
    if len(adr_files) < 12:
        raise SystemExit(f"Expected >= 12 ADRs in {ADR_DIR}, found {len(adr_files)}")

    rows = [parse_adr(p) for p in adr_files]
    rendered = render_catalog(rows)

    if args.check:
        if not CATALOG_PATH.is_file():
            raise SystemExit("CATALOG.md missing; run scripts/architecture_catalog.py")
        current = CATALOG_PATH.read_text(encoding="utf-8")
        if current != rendered:
            raise SystemExit("CATALOG.md is out of sync with docs/adr/ADR-*.md")
        print(f"ADR catalog verified: {len(rows)} ADRs valid, 0 drift.")
        return 0

    CATALOG_PATH.write_text(rendered, encoding="utf-8")
    print(f"Wrote {CATALOG_PATH} ({len(rows)} ADRs).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
